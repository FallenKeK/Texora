// Перевод интерфейса: строки интерфейса пишутся по-русски и переводятся при выводе.
func (a *App) tr(s string) string {
	if a.Set.Lang == "en" {
		if t, ok := enUI[s]; ok {
			return t
		}
	}
	return s
}

func (a *App) trf(format string, args ...any) string { return fmt.Sprintf(a.tr(format), args...) }

func (a *App) measure(s string, f Font) float64 { return a.tb.Measure(a.tr(s), f) }

